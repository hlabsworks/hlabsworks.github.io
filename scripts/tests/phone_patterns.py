"""電話番号らしき文字列を検出するロジック。site-structure-test.sh の個人情報検査本体と、
その回帰テスト（見逃し例・誤検出例のフィクスチャ検査）の両方から共有する。
検査本体だけ直しても回帰テストが古い正規表現のコピーのままだと、テストが検査本体の
変更を追随せず「検査なしで合格」に近い状態になりうるため、定義を1か所にまとめる。

区切り文字にはハイフン各種（半角/全角/長音符/U+2212/enダッシュ/emダッシュ）・ドット・空白・
カッコを許容し、`+81 99 000 0000`（国番号の後に空白）・`+81(0)99-000-0000`（国番号の後に
(0)）・`(03) 1234-5678`（市外局番を丸ごと括弧で囲む）・`(099)000-0000`（市外局番の括弧の
直後に区切り無し）・`099.000.0000`（ドット区切り）も検出する。フリーダイヤル(0120/0800)は
ビジネス用途で個人情報ではないため対象外。`05-10-2026`のような日付(月-日-年)は桁数だけでは
電話番号と区別できないため、3つ組の各値を月(1-12)・日(1-31)・西暦(1900-2099)として解釈
できる場合は日付とみなして除外する。全角数字・全角記号はNFKCで正規化してから照合する。
小数部(`12.0123456789`のような桁数の多い小数)を誤検出しないよう、連続数字パターンの
直前が数字またはドットの場合は除外する。`0.00 0.00 0.000`のような小数の羅列を誤検出
しないよう、市外局番の次(中間)の桁は3桁以上を必須にする（日本の電話番号で中間部が
1〜2桁のものは無いため、実在の電話番号の見逃しにはならない）。
"""
from __future__ import annotations

import re
import unicodedata

_SEP1 = r'[-‐－ー−–—.(（\s]'
_SEP2 = r'[-‐－ー−–—.)）\s]'

PHONE_RE = re.compile(
    r'(?<!\d)(?:(\+81)[-‐－\s]?(?:\(0\)[-‐－\s]?)?|\(?(0)(?!120|800))'
    # 市外局番を`(099)`のように括弧で囲んだ場合、閉じ括弧の直後は区切り文字が無くても
    # 電話番号とみなす（`(099)000-0000`）。括弧が無い場合は従来どおり区切り文字を必須にする。
    r'(\d{1,4})(?:\)' + _SEP1 + r'?|' + _SEP1 + r')(\d{3,4})' + _SEP2 + r'(\d{3,4})(?!\d)'
)
PHONE_PLAIN_RE = re.compile(r'(?<![\d.])0(?!120|800)\d{9,10}(?!\d)')


def _looks_like_date(g1: str, g2: str, g3: str) -> bool:
    if len(g3) != 4:
        return False
    try:
        a, b, c = int(g1), int(g2), int(g3)
    except ValueError:
        return False
    return 1900 <= c <= 2099 and 1 <= a <= 12 and 1 <= b <= 31


def is_phone_like(text: str) -> bool:
    text = unicodedata.normalize("NFKC", text)
    if PHONE_PLAIN_RE.search(text):
        return True
    for m in PHONE_RE.finditer(text):
        is_intl, is_domestic, g1, g2, g3 = m.groups()
        if is_intl:
            return True  # +81表記は日付との衝突がないため常に電話番号とみなす
        if not _looks_like_date(g1, g2, g3):
            return True
    return False
